using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System;
using System.Linq;
using System.Text;

namespace NacreCraft.SourceGenerator;

//Expands the N-ary record codec factories that C# cannot express without variadic generics
//The emitted bodies mirror the hand written ones one for one, so the generated IL is unchanged;
//only the 1..N repetition leaves the source tree and lives in this single template
[Generator]
public sealed class RecordCodecGenerator : IIncrementalGenerator
{
    private const string AttributeName = "NacreCraft.Codec.GenerateRecordCodecsAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var targets = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => Extract(ctx))
            .Where(static target => target.HasValue)
            .Select(static (target, _) => target!.Value);

        context.RegisterSourceOutput(targets, static (spc, target) => Emit(spc, target));
    }

    private static TargetInfo? Extract(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol symbol) return null;

        var attribute = context.Attributes.FirstOrDefault();
        if (attribute is null) return null;

        var maxFields = 16;
        if (attribute.ConstructorArguments.Length > 0
            && attribute.ConstructorArguments[0].Value is int declared)
        {
            maxFields = declared;
        }
        if (maxFields < 1) return null;

        var accessibility = symbol.DeclaredAccessibility switch
        {
            Accessibility.Public => "public ",
            Accessibility.Internal => "internal ",
            Accessibility.Private => "private ",
            _ => string.Empty,
        };

        return new TargetInfo(
            symbol.Name,
            symbol.ContainingNamespace?.ToDisplayString() ?? string.Empty,
            accessibility,
            symbol.IsStatic,
            maxFields);
    }

    private static void Emit(SourceProductionContext context, TargetInfo target)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable disable");
        builder.AppendLine();

        if (target.Namespace.Length > 0)
        {
            builder.AppendLine($"namespace {target.Namespace};");
            builder.AppendLine();
        }

        builder.AppendLine($"{target.Accessibility}{(target.IsStatic ? "static " : string.Empty)}partial class {target.Name}");
        builder.AppendLine("{");
        for (var count = 1; count <= target.MaxFields; count++)
        {
            AppendFactory(builder, count);
        }
        builder.AppendLine("}");

        for (var count = 1; count <= target.MaxFields; count++)
        {
            AppendCodec(builder, count);
        }

        context.AddSource($"{target.Name}.g.cs", builder.ToString());
    }

    private static void AppendFactory(StringBuilder builder, int count)
    {
        var typeArguments = string.Join(", ", Enumerable.Range(1, count).Select(index => $"F{index}"));

        builder.AppendLine($"    public static Codec<T> Of{count}<T, {typeArguments}>(");
        for (var index = 1; index <= count; index++)
        {
            builder.Append($"        FieldCodec<T, F{index}> f{index}");
            builder.AppendLine(index == count ? "," : ",");
        }
        builder.AppendLine($"        Func<{typeArguments}, T> ctor)");
        builder.AppendLine($"        => new RecordCodec{count}<T, {typeArguments}>({string.Join(", ", Enumerable.Range(1, count).Select(index => $"f{index}"))}, ctor);");
        builder.AppendLine();
    }

    private static void AppendCodec(StringBuilder builder, int count)
    {
        var typeArguments = string.Join(", ", Enumerable.Range(1, count).Select(index => $"F{index}"));

        builder.AppendLine($"//{count}-field record codec");
        builder.AppendLine($"internal sealed class RecordCodec{count}<T, {typeArguments}> : AbstractMapCodec<T>");
        builder.AppendLine("{");
        for (var index = 1; index <= count; index++)
        {
            builder.AppendLine($"    private readonly FieldCodec<T, F{index}> _f{index};");
        }
        builder.AppendLine($"    private readonly Func<{typeArguments}, T> _ctor;");
        builder.AppendLine();

        builder.AppendLine($"    public RecordCodec{count}(");
        for (var index = 1; index <= count; index++)
        {
            builder.AppendLine($"        FieldCodec<T, F{index}> f{index},");
        }
        builder.AppendLine($"        Func<{typeArguments}, T> ctor)");
        builder.AppendLine("    {");
        builder.AppendLine($"        {string.Join(" ", Enumerable.Range(1, count).Select(index => $"_f{index} = f{index};"))} _ctor = ctor;");
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.AppendLine("    public override DataResult<T> Decode<U>(DynamicOps<U> ops, MapLike<U> input)");
        builder.AppendLine("    {");
        for (var index = 1; index <= count; index++)
        {
            builder.AppendLine($"        var r{index} = _f{index}.Codec.Decode(ops, input);");
            builder.AppendLine($"        if (!r{index}.TryGet(out var v{index})) return Fail(r{index});");
        }
        builder.AppendLine($"        return DataResult<T>.Success(_ctor({string.Join(", ", Enumerable.Range(1, count).Select(index => $"v{index}"))}));");
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.AppendLine("    public override RecordBuilder<U> EncodeTo<U>(DynamicOps<U> ops, T value, RecordBuilder<U> builder)");
        builder.AppendLine("    {");
        for (var index = 1; index <= count; index++)
        {
            builder.AppendLine($"        _f{index}.Codec.EncodeTo(ops, _f{index}.Getter(value), builder);");
        }
        builder.AppendLine("        return builder;");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private readonly struct TargetInfo : IEquatable<TargetInfo>
    {
        public readonly string Name;
        public readonly string Namespace;
        public readonly string Accessibility;
        public readonly bool IsStatic;
        public readonly int MaxFields;

        public TargetInfo(string name, string @namespace, string accessibility, bool isStatic, int maxFields)
        {
            Name = name;
            Namespace = @namespace;
            Accessibility = accessibility;
            IsStatic = isStatic;
            MaxFields = maxFields;
        }

        public bool Equals(TargetInfo other)
            => Name == other.Name
               && Namespace == other.Namespace
               && Accessibility == other.Accessibility
               && IsStatic == other.IsStatic
               && MaxFields == other.MaxFields;

        public override bool Equals(object? obj) => obj is TargetInfo other && Equals(other);

        public override int GetHashCode()
        {
            unchecked
            {
                var hash = Name.GetHashCode();
                hash = (hash * 397) ^ Namespace.GetHashCode();
                hash = (hash * 397) ^ Accessibility.GetHashCode();
                hash = (hash * 397) ^ IsStatic.GetHashCode();
                hash = (hash * 397) ^ MaxFields;
                return hash;
            }
        }
    }
}
